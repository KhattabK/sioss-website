-- SIOSS online courses: paid access, lesson content, progress, final exam, certificates.
-- Run once in Supabase: Dashboard → SQL Editor → New query → paste → Run.
-- Requires schema.sql (students, admins, is_admin) to have been run first.
-- Lesson content itself is loaded by a separate file that is NOT kept in this repository.

-- ── Tables ──

-- Who has paid for which course. Rows are written by the stripe-webhook function (or by an admin by hand).
create table if not exists public.course_access (
  id             bigint generated by default as identity primary key,
  course         text not null,
  user_id        uuid references auth.users (id) on delete set null,
  email          text,                         -- lower-case; used when the buyer paid before signing in
  stripe_session text unique,
  created_at     timestamptz not null default now(),
  check (user_id is not null or email is not null)
);

-- Lessons. n = 1..13 are units; kind 'exam' is the final exam (its html carries no answer marks).
create table if not exists public.course_units (
  course    text not null,
  n         int  not null,
  kind      text not null default 'unit',
  section   text not null default '',
  title     text not null,
  meta      text not null default '',
  video_url text,
  html      text not null,
  primary key (course, n)
);

-- Final-exam answer key: index (0-based) of the correct option per question. Never readable by clients.
create table if not exists public.course_exam_keys (
  course  text primary key,
  answers int[] not null,
  pass    int   not null
);

create table if not exists public.course_progress (
  user_id   uuid not null references auth.users (id) on delete cascade,
  course    text not null,
  n         int  not null,
  score     int  not null,
  passed_at timestamptz not null default now(),
  primary key (user_id, course, n)
);

create table if not exists public.course_exam_attempts (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users (id) on delete cascade,
  course     text not null,
  score      int  not null,
  passed     boolean not null,
  created_at timestamptz not null default now()
);

create table if not exists public.course_certificates (
  cert_no   text primary key,
  user_id   uuid not null references auth.users (id) on delete cascade,
  course    text not null,
  name      text not null,
  issued_at date not null default current_date,
  unique (user_id, course)
);

create sequence if not exists public.course_cert_seq;

-- ── Access check ──
create or replace function public.has_course_access(p_course text)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select public.is_admin() or exists (
    select 1 from public.course_access a
    where a.course = p_course
      and (a.user_id = auth.uid() or a.email = lower(auth.jwt() ->> 'email'))
  );
$$;

-- ── Row Level Security ──
alter table public.course_access        enable row level security;
alter table public.course_units         enable row level security;
alter table public.course_exam_keys     enable row level security;
alter table public.course_progress      enable row level security;
alter table public.course_exam_attempts enable row level security;
alter table public.course_certificates  enable row level security;

drop policy if exists "Admins manage access" on public.course_access;
create policy "Admins manage access"
  on public.course_access for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Paid users read lessons" on public.course_units;
create policy "Paid users read lessons"
  on public.course_units for select to authenticated
  using (public.has_course_access(course));

drop policy if exists "Users read own progress" on public.course_progress;
create policy "Users read own progress"
  on public.course_progress for select to authenticated
  using (user_id = auth.uid());

drop policy if exists "Users record own progress" on public.course_progress;
create policy "Users record own progress"
  on public.course_progress for insert to authenticated
  with check (user_id = auth.uid() and public.has_course_access(course));

drop policy if exists "Users update own progress" on public.course_progress;
create policy "Users update own progress"
  on public.course_progress for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "Users read own attempts" on public.course_exam_attempts;
create policy "Users read own attempts"
  on public.course_exam_attempts for select to authenticated
  using (user_id = auth.uid());

drop policy if exists "Users read own certificate" on public.course_certificates;
create policy "Users read own certificate"
  on public.course_certificates for select to authenticated
  using (user_id = auth.uid() or public.is_admin());

-- course_exam_keys has no policy on purpose: only the function below can read it.

-- ── Final exam: graded on the server, issues the certificate and adds the graduate to the registry ──
create or replace function public.submit_final_exam(p_course text, p_answers int[], p_name text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  k        public.course_exam_keys%rowtype;
  v_units  int;
  v_done   int;
  v_score  int := 0;
  v_passed boolean;
  v_cert   text;
  v_title  text;
  i        int;
begin
  if auth.uid() is null or not public.has_course_access(p_course) then
    raise exception 'no access';
  end if;

  select * into k from public.course_exam_keys where course = p_course;
  if not found then raise exception 'no exam'; end if;
  if coalesce(array_length(p_answers, 1), 0) <> array_length(k.answers, 1) then
    raise exception 'answer every question';
  end if;

  select count(*) into v_units from public.course_units where course = p_course and kind = 'unit';
  select count(*) into v_done  from public.course_progress where course = p_course and user_id = auth.uid();
  if v_done < v_units then raise exception 'finish all unit quizzes first'; end if;

  -- At most 3 attempts per 24 hours.
  if (select count(*) from public.course_exam_attempts
      where user_id = auth.uid() and course = p_course and created_at > now() - interval '24 hours') >= 3 then
    return json_build_object('error', 'too_many_attempts');
  end if;

  for i in 1 .. array_length(k.answers, 1) loop
    if p_answers[i] = k.answers[i] then v_score := v_score + 1; end if;
  end loop;
  v_passed := v_score >= k.pass;

  insert into public.course_exam_attempts (user_id, course, score, passed)
  values (auth.uid(), p_course, v_score, v_passed);

  if v_passed then
    select cert_no into v_cert from public.course_certificates where user_id = auth.uid() and course = p_course;
    if v_cert is null then
      if length(trim(coalesce(p_name, ''))) < 3 then raise exception 'name required'; end if;
      v_cert  := 'SIOSS-' || upper(p_course) || '-' || to_char(current_date, 'YYYY') || '-' ||
                 lpad(nextval('public.course_cert_seq')::text, 4, '0');
      v_title := case p_course when 'ffc' then 'Football Fitness Coach (Online)' else p_course end;
      insert into public.course_certificates (cert_no, user_id, course, name)
      values (v_cert, auth.uid(), p_course, trim(p_name));
      insert into public.students (name, course, date, instructor)
      values (trim(p_name), v_title, to_char(current_date, 'MM/DD/YYYY'), 'Fredrik Björs');
    end if;
  end if;

  return json_build_object('score', v_score, 'total', array_length(k.answers, 1),
                           'pass', k.pass, 'passed', v_passed, 'cert_no', v_cert);
end;
$$;

revoke all on function public.submit_final_exam(text, int[], text) from public, anon;
grant execute on function public.submit_final_exam(text, int[], text) to authenticated;

