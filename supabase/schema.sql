-- Run once in Supabase: Dashboard → SQL Editor → New query → paste → Run.

-- ── Tables ──
create table if not exists public.students (
  id          bigint generated by default as identity primary key,
  name        text not null,
  course      text not null default '',
  date        text not null default '',   -- MM/DD/YYYY, same format as before
  instructor  text not null default '',
  created_at  timestamptz not null default now()
);

-- Users listed here may add/remove students.
create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- ── Row Level Security ──
alter table public.students enable row level security;
alter table public.admins   enable row level security;

drop policy if exists "Public can read students" on public.students;
create policy "Public can read students"
  on public.students for select
  to anon, authenticated
  using (true);

drop policy if exists "Admins can insert students" on public.students;
create policy "Admins can insert students"
  on public.students for insert
  to authenticated
  with check (public.is_admin());

drop policy if exists "Admins can update students" on public.students;
create policy "Admins can update students"
  on public.students for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Admins can delete students" on public.students;
create policy "Admins can delete students"
  on public.students for delete
  to authenticated
  using (public.is_admin());

